// Generates app/api/schema.d.ts from the backend's OpenAPI document.
//   npm run api:generate          write the file
//   npm run api:check             fail when the committed file differs from what the backend serves now
// OPENAPI_URL picks the document, default the dev backend (Swagger is switched off in prod).
import { readFile, writeFile } from "node:fs/promises";

import openapiTS, { astToString } from "openapi-typescript";

const url = process.env.OPENAPI_URL ?? "https://api-dev-narrativ.rizkysiregar.my.id/api/v1/v3/api-docs";
const target = new URL("../app/api/schema.d.ts", import.meta.url);
const check = process.argv.includes("--check");

const header = `/**
 * Generated by scripts/api-generate.mjs from the backend's OpenAPI document. Do not edit by hand:
 * run \`npm run api:generate\` after a backend change.
 */

`;

// alphabetized, so a reordering on the backend does not show up as a diff
const ast = await openapiTS(new URL(url), { alphabetize: true });
const generated = header + astToString(ast);

if (check) {
  const committed = await readFile(target, "utf8").catch(() => "");
  if (committed !== generated) {
    console.error(`app/api/schema.d.ts is out of date with ${url}. Run npm run api:generate.`);
    process.exit(1);
  }
  console.log("app/api/schema.d.ts matches the backend.");
} else {
  await writeFile(target, generated);
  console.log(`app/api/schema.d.ts generated from ${url}.`);
}
