// Writes build/nginx/security-headers.conf after `react-router build`. The Content-Security-Policy allows the inline
// scripts React Router puts into index.html by their SHA-256 hash, so no 'unsafe-inline' is needed for scripts.
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

/** The hashes of the inline (src-less) scripts of an HTML document, in CSP source form. */
export function inlineScriptHashes(html) {
  const hashes = [];
  for (const [, attributes, body] of html.matchAll(/<script([^>]*)>([\s\S]*?)<\/script>/g)) {
    if (!/\ssrc=/.test(attributes)) {
      hashes.push(`'sha256-${createHash("sha256").update(body).digest("base64")}'`);
    }
  }
  return hashes;
}

// Post media and profile pictures: presigned URLs of the MinIO host, the same one for dev and prod (bucket differs)
export const MEDIA_ORIGIN = "https://infra-minio.rizkysiregar.my.id";
// what Firebase Messaging calls to register a browser for web push (the push itself arrives through the browser)
export const PUSH_ORIGINS = [
  "https://firebaseinstallations.googleapis.com",
  "https://fcmregistrations.googleapis.com",
];

// Google Identity Services (Sign in with Google), as Google documents for a CSP: its script, the button's stylesheet
// and iframe, and the calls the button makes
export const GOOGLE_SIGN_IN = "https://accounts.google.com/gsi/";

// Cloudflare Web Analytics: Cloudflare injects its beacon into the page at the edge, and the beacon reports there
export const CLOUDFLARE_ANALYTICS = {
  script: "https://static.cloudflareinsights.com",
  connect: "https://cloudflareinsights.com",
};

/** Where Sentry events go: the origin of the project's DSN, when the build has one. */
export function sentryOrigin(dsn) {
  if (!dsn) {
    return null;
  }
  return new URL(dsn).origin;
}

export function contentSecurityPolicy(scriptHashes, { sentryDsn } = {}) {
  const sentry = sentryOrigin(sentryDsn);
  return [
    "default-src 'self'",
    `script-src 'self' ${GOOGLE_SIGN_IN}client ${CLOUDFLARE_ANALYTICS.script} ${scriptHashes.join(" ")}`.trim(),
    // sonner injects its stylesheet at runtime; inline styles cannot run code, inline scripts stay blocked
    `style-src 'self' 'unsafe-inline' ${GOOGLE_SIGN_IN}style`,
    `img-src 'self' data: blob: ${MEDIA_ORIGIN}`,
    `media-src 'self' blob: ${MEDIA_ORIGIN}`,
    "font-src 'self'",
    // the API is same-origin (the ingress routes /api to the backend); post media upload straight to MinIO
    [
      "connect-src 'self'",
      MEDIA_ORIGIN,
      ...PUSH_ORIGINS,
      GOOGLE_SIGN_IN,
      CLOUDFLARE_ANALYTICS.connect,
      ...(sentry ? [sentry] : []),
    ].join(" "),
    `frame-src ${GOOGLE_SIGN_IN}`,
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join("; ");
}

export function securityHeaders(csp) {
  return `# Generated by scripts/csp.mjs at build time. Included at server level and again in every location that sets its
# own add_header, because nginx drops inherited add_header directives as soon as a location has one.
add_header Content-Security-Policy "${csp}" always;
add_header X-Content-Type-Options nosniff always;
add_header X-Frame-Options DENY always;
add_header Referrer-Policy strict-origin-when-cross-origin always;
add_header Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=()" always;
# allow-popups: the Sign in with Google popup must be able to hand its answer back to this window
add_header Cross-Origin-Opener-Policy same-origin-allow-popups always;
# everything is behind sign-in: nothing to index (public/robots.txt says the same)
add_header X-Robots-Tag "noindex, nofollow" always;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const html = await readFile("build/client/index.html", "utf8");
  const hashes = inlineScriptHashes(html);
  await mkdir("build/nginx", { recursive: true });
  const csp = contentSecurityPolicy(hashes, { sentryDsn: process.env.VITE_SENTRY_DSN });
  await writeFile("build/nginx/security-headers.conf", securityHeaders(csp));
  console.log(`build/nginx/security-headers.conf written (${hashes.length} inline script hashes).`);
}
